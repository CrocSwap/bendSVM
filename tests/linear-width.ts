import fs from 'node:fs';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {main,boundInventory} from '../verification/check-linear-width.ts';
import {digest} from '../verification/check-acyclic-lowering.ts';
import {processControls} from './linear-width-process.ts';
const output='build/linear-width-test.json';
if(fs.existsSync(output))fs.renameSync(output,`${output}.${Date.now()}.previous`);
await main();
const failures=processControls();
await main();
const receiptPath='build/linear-width/fresh-receipt.json',raw=fs.readFileSync(receiptPath),receipt=JSON.parse(raw.toString());
const run=receipt.inputs[0].artifact.replace(/\/input\.json$/,'');
const result=spawnSync(process.env.PYTHON??'python3',['-B','tests/linear-width-reports.py'],{encoding:'utf8',timeout:30000,maxBuffer:4*1024*1024});
const log=`${run}/report-controls.log`;fs.writeFileSync(log,(result.stdout??'')+(result.stderr??''));
assert.ifError(result.error);assert.equal(result.signal,null);assert.equal(result.status,0,result.stderr);
const artifact=`${run}/report-controls.json`,controls=JSON.parse(fs.readFileSync(artifact,'utf8'));
assert.equal(controls.passed,true);assert.equal(controls.runId,receipt.runId);assert.equal(controls.refusals.length,47);
const semantic=spawnSync(process.env.PYTHON??'python3',['-B','tests/linear-width-semantics.py'],{encoding:'utf8',timeout:180000,maxBuffer:4*1024*1024});
const semanticLog=`${run}/source-controls.log`;fs.writeFileSync(semanticLog,(semantic.stdout??'')+(semantic.stderr??''));
assert.ifError(semantic.error);assert.equal(semantic.signal,null);assert.equal(semantic.status,0,semanticLog);
const semanticArtifact=`${run}/source-controls.json`,semanticReport=JSON.parse(fs.readFileSync(semanticArtifact,'utf8'));
assert.equal(semanticReport.passed,true);assert.equal(semanticReport.runId,receipt.runId);assert.equal(semanticReport.controls.length,3);
assert.deepEqual(boundInventory(),receipt.sourceHashes);assert.deepEqual(fs.readFileSync(receiptPath),raw);
fs.writeFileSync('build/linear-width-test.json',JSON.stringify({passed:true,endToEndVerified:false,processControls:failures,semanticArtifact,semanticSha256:digest(fs.readFileSync(semanticArtifact)),semanticLog,semanticLogSha256:digest(fs.readFileSync(semanticLog)),receiptArtifact:receiptPath,receiptSha256:digest(raw),controlsArtifact:artifact,controlsSha256:digest(fs.readFileSync(artifact)),log,logSha256:digest(fs.readFileSync(log))},null,2)+'\n');
console.log('Linear source composition, 47 report refusals, four process failures and three source mutations passed');
